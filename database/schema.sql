CREATE TABLE IF NOT EXISTS pengguna (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(150) NOT NULL,
    email VARCHAR(255) UNIQUE,
    nis VARCHAR(50) UNIQUE,
    kata_sandi VARCHAR(255) NOT NULL,
    peran VARCHAR(20) NOT NULL CHECK (peran IN ('guru', 'siswa')),
    tingkat VARCHAR(10),
    rombel VARCHAR(10),
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS materi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mapel VARCHAR(100) NOT NULL,
    tingkat VARCHAR(10) NOT NULL,
    rombel TEXT[] NOT NULL DEFAULT '{}',
    judul VARCHAR(255) NOT NULL,
    teks TEXT[] NOT NULL DEFAULT '{}',
    rangkuman TEXT[] NOT NULL DEFAULT '{}',
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    diubah_pada TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS soal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    materi_id BIGINT REFERENCES materi(id) ON DELETE CASCADE,
    topik VARCHAR(150),
    tanya TEXT NOT NULL,
    opsi TEXT[] NOT NULL,
    jawaban INTEGER NOT NULL,
    kelas TEXT[] NOT NULL DEFAULT '{}',
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS hasil (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengguna_id BIGINT NOT NULL REFERENCES pengguna(id) ON DELETE CASCADE,
    materi_id BIGINT REFERENCES materi(id) ON DELETE SET NULL,
    nilai NUMERIC(5,2) NOT NULL,
    benar INTEGER NOT NULL DEFAULT 0,
    total INTEGER NOT NULL DEFAULT 0,
    detail JSONB NOT NULL DEFAULT '[]',
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS aktivitas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengguna_id BIGINT REFERENCES pengguna(id) ON DELETE SET NULL,
    jenis VARCHAR(100) NOT NULL,
    keterangan TEXT,
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS chat (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pengguna_id BIGINT NOT NULL REFERENCES pengguna(id) ON DELETE CASCADE,
    pertanyaan TEXT NOT NULL,
    jawaban TEXT,
    materi_id BIGINT REFERENCES materi(id) ON DELETE SET NULL,
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ringkasan_harian (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tanggal DATE NOT NULL,
    kelas VARCHAR(20) NOT NULL,
    jumlah_latihan INTEGER NOT NULL DEFAULT 0,
    rata_rata NUMERIC(5,2) NOT NULL DEFAULT 0,
    dibuat_pada TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (tanggal, kelas)
);